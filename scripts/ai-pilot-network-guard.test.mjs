import assert from "node:assert/strict";
import { test } from "node:test";
import { createAiPilotFetch } from "./ai-pilot-network-guard.mjs";
const origin = "https://example.supabase.co", model = "openai/gpt-4.1";
const modelUrl = "https://openrouter.ai/api/v1/chat/completions", sendUrl = "https://api.ycloud.com/v2/whatsapp/messages";
const body = { model, messages: [{ role: "user", content: "Synthetic test" }], max_tokens: 1024 };
const expectedSend = { from: "+15555550100", to: "+15555550101", operationId: "test-operation", body: "Approved test" };
const send = { from: expectedSend.from, to: expectedSend.to, externalId: "channel:test-operation", type: "text", text: { body: expectedSend.body } };
const post = (value) => ({ method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(value) });
function fixture(phase = "generate") {
  const calls = [], ledger = { modelRequests: 0, providerPosts: 0 }, persisted = [];
  const options = { phase, projectOrigin: origin, model, expectedSend, ledger, persist: async () => { persisted.push({ ...ledger }); },
    fetchImpl: async (request) => { calls.push(request); return new Response("{}"); } };
  return { calls, ledger, persisted, options, guarded: createAiPilotFetch(options) };
}
test("model request is pinned, output capped and attempt recorded before network", async () => {
  const f = fixture(); await f.guarded(modelUrl, post(body));
  assert.equal((await f.calls[0].json()).max_tokens, 128);
  assert.equal(f.calls[0].redirect, "error");
  assert.deepEqual(f.persisted, [{ modelRequests: 1, providerPosts: 0 }]);
  await assert.rejects(f.guarded(modelUrl, post(body)), /AI_PILOT_NETWORK_DENIED/); assert.equal(f.calls.length, 1);
});
test("model tools, extra models, wrong model, images and oversized context cannot run", async () => {
  const f = fixture();
  for (const patch of [{ tools: [{}] }, { models: [model] }, { model: "other" }, { stream: true },
    { messages: [{ role: "user", content: [] }] }, { messages: [{ role: "user", content: "x".repeat(16001) }] }]) {
    await assert.rejects(f.guarded(modelUrl, post({ ...body, ...patch })), /AI_PILOT_NETWORK_DENIED/);
  }
  assert.equal(f.calls.length, 0); assert.equal(f.persisted.length, 0);
});
test("a failed persisted attempt cannot be regenerated by a later runner", async () => {
  const f = fixture(); f.options.fetchImpl = async () => { throw new Error("Synthetic timeout"); };
  await assert.rejects(createAiPilotFetch(f.options)(modelUrl, post(body)), /Synthetic timeout/);
  await assert.rejects(createAiPilotFetch(f.options)(modelUrl, post(body)), /AI_PILOT_NETWORK_DENIED/);
  assert.equal(f.ledger.modelRequests, 1);
});
test("no network request runs if the attempt ledger could not be persisted", async () => {
  const f = fixture(); f.options.persist = async () => { throw new Error("Synthetic disk failure"); };
  await assert.rejects(createAiPilotFetch(f.options)(modelUrl, post(body)), /Synthetic disk failure/);
  assert.equal(f.calls.length, 0);
});
test("send phase allows one exact approved recipient, text, account and operation", async () => {
  const f = fixture("send");
  for (const patch of [{ to: "+15555550999" }, { from: "+15555550999" }, { text: { body: "Changed" } }, { externalId: "other" }, { template: {} }]) {
    await assert.rejects(f.guarded(sendUrl, post({ ...send, ...patch })), /AI_PILOT_NETWORK_DENIED/);
  }
  await f.guarded(sendUrl, post(send)); await assert.rejects(f.guarded(sendUrl, post(send)), /AI_PILOT_NETWORK_DENIED/);
  assert.equal(f.calls.length, 1); assert.equal(f.persisted[0].providerPosts, 1);
});
test("model and send phases cannot execute each other's external side effect", async () => {
  await assert.rejects(fixture().guarded(sendUrl, post(send)), /AI_PILOT_NETWORK_DENIED/);
  await assert.rejects(fixture("send").guarded(modelUrl, post(body)), /AI_PILOT_NETWORK_DENIED/);
});
test("Supabase origin is exact and embeddings, CRM, judge and provider redirects are excluded", async () => {
  const f = fixture(); await f.guarded(`${origin}/rest/v1/messages`);
  for (const url of ["https://foreign.supabase.co/rest/v1/messages", "https://openrouter.ai/api/v1/embeddings",
    "https://api.typesafe.ai/judge", "https://crm.example.invalid", "https://api.ycloud.com/v2/whatsapp/messages/sendDirectly"]) {
    await assert.rejects(f.guarded(url, post(body)), /AI_PILOT_NETWORK_DENIED/);
  }
  assert.equal(f.calls.length, 1);
});
